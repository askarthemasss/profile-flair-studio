/**
 * Sigil GitHub Action — Static SVG Backup.
 *
 * Uses the user's own GitHub token (no Sigil server dependency) to fetch
 * stats via GraphQL and commit static SVG copies of all nine cards.
 *
 * Inputs are read from environment variables set by the Actions runner.
 */

import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import {
  STATS_QUERY,
  CardIdSchema,
  CARD_IDS,
  type CardId,
} from "@sigil/core";

// ---------------------------------------------------------------------------
// Read Action inputs
// ---------------------------------------------------------------------------

function getInput(name: string, required = true): string {
  const env = process.env[`INPUT_${name.toUpperCase().replace(/-/g, "_")}`];
  if (required && !env) {
    console.error(`::error::Missing required input: ${name}`);
    process.exit(1);
  }
  return env ?? "";
}

const token = getInput("github-token");
const username = getInput("username");
const theme = getInput("theme") || "obsidian";
const outputDir = getInput("output-dir") || ".sigil";
const cardsInput = getInput("cards") || CARD_IDS.join(",");

const requestedKinds = cardsInput
  .split(",")
  .map((s) => s.trim())
  .filter((s) => {
    const parsed = CardIdSchema.safeParse(s);
    if (!parsed.success) console.warn(`::warning::Unknown card kind "${s}", skipping`);
    return parsed.success;
  }) as CardId[];

// ---------------------------------------------------------------------------
// GitHub GraphQL helper
// ---------------------------------------------------------------------------

async function gql<T>(query: string, variables: Record<string, string>): Promise<T> {
  const res = await fetch("https://api.github.com/graphql", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json",
      "User-Agent": "sigil-action/0.1.0",
    },
    body: JSON.stringify({ query, variables }),
  });
  if (!res.ok) throw new Error(`GitHub API error: ${res.status} ${res.statusText}`);
  const json = (await res.json()) as { data: T; errors?: unknown[] };
  if (json.errors?.length) throw new Error(`GraphQL errors: ${JSON.stringify(json.errors)}`);
  return json.data;
}

// ---------------------------------------------------------------------------
// SVG generation (placeholder — will call @sigil/core renderers)
// ---------------------------------------------------------------------------

function generateSvg(kind: CardId, _data: unknown): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="495" height="195" viewBox="0 0 495 195">
  <rect width="495" height="195" rx="8" fill="#121115"/>
  <text x="24" y="40" font-family="monospace" fill="#F3EFE8" font-size="14" opacity="0.5">
    ${kind} · ${theme}
  </text>
  <text x="24" y="68" font-family="monospace" fill="#F3EFE8" font-size="22" font-weight="600">
    @${username}
  </text>
  <text x="24" y="96" font-family="monospace" fill="#F3EFE8" font-size="12" opacity="0.4">
    Generated by Sigil Action — static backup
  </text>
</svg>`;
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function run() {
  console.log(`::group::Sigil — generating ${requestedKinds.length} cards for @${username}`);

  // Fetch data using the user's own token — no Sigil server involved.
  const stats = await gql(STATS_QUERY, { login: username });

  // Write SVGs to output dir.
  const workspace = process.env["GITHUB_WORKSPACE"] ?? ".";
  const dir = join(workspace, outputDir);
  mkdirSync(dir, { recursive: true });

  let filesWritten = 0;
  for (const kind of requestedKinds) {
    const svg = generateSvg(kind, { stats });
    const filePath = join(dir, `${kind}.svg`);
    writeFileSync(filePath, svg, "utf-8");
    console.log(`  ✓ ${kind}.svg`);
    filesWritten++;
  }

  // Set output for downstream steps.
  const outputFile = process.env["GITHUB_OUTPUT"];
  if (outputFile) {
    writeFileSync(outputFile, `files-written=${filesWritten}\n`, { flag: "a" });
  }

  console.log(`::endgroup::`);
  console.log(`✓ ${filesWritten} SVG files written to ${outputDir}/`);
}

run().catch((err: unknown) => {
  console.error("::error::", err instanceof Error ? err.message : err);
  process.exit(1);
});
